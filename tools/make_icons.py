"""Generate FamilyShield launcher icons from the master artwork.

Source of truth: art/ic_launcher_source.png (the neon family-shield emblem).
Everything under app/res/mipmap-* and the adaptive foreground layer is derived
from it, so the icon can be regenerated after the artwork changes:

    python tools/make_icons.py

Outputs
-------
mipmap-{mdpi,hdpi,xhdpi,xxhdpi,xxxhdpi}/ic_launcher.png        48..192 px, full bleed
mipmap-{...}/ic_launcher_round.png                              circular mask, 10% inset
drawable-nodpi/ic_launcher_art.png                              432 px adaptive foreground
drawable/ic_launcher_background.xml                             solid colour sampled from the art
assets/www/img/emblem.png                                       256 px in-app brand mark
"""

from __future__ import annotations

import hashlib
import pathlib

from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "art" / "ic_launcher_source.png"
RES = ROOT / "app" / "res"

# Legacy launcher bitmaps (Android 6/7 and non-adaptive launchers).
DENSITIES = {
    "mdpi": 48,
    "hdpi": 72,
    "xhdpi": 96,
    "xxhdpi": 144,
    "xxxhdpi": 192,
}

# Adaptive icon: 108 dp layer, 72 dp safe zone. The artwork content spans ~88%
# of the source canvas, so scaling the canvas to 75% keeps the content inside
# the safe zone on every mask shape (circle, squircle, rounded square).
ADAPTIVE_SIZE = 432
FOREGROUND_SCALE = 0.70
ROUND_SCALE = 0.90

# In-app header mark (rendered at 40 dp, so 256 px stays crisp on 3x screens).
WEB_SIZE = 256


def edge_colour(img: Image.Image) -> tuple[int, int, int]:
    """Average colour of the outermost ring - the emblem's background tone."""
    w, h = img.size
    px = img.load()
    step = max(1, min(w, h) // 64)
    total = [0, 0, 0]
    count = 0
    for x in range(0, w, step):
        for y in (0, 1, h - 2, h - 1):
            r, g, b = px[x, y][:3]
            total[0] += r
            total[1] += g
            total[2] += b
            count += 1
    for y in range(0, h, step):
        for x in (0, 1, w - 2, w - 1):
            r, g, b = px[x, y][:3]
            total[0] += r
            total[1] += g
            total[2] += b
            count += 1
    return tuple(round(c / max(1, count)) for c in total)  # type: ignore[return-value]


def on_canvas(img: Image.Image, size: int, scale: float, background: tuple[int, int, int]) -> Image.Image:
    """Centre `img` on a square canvas of `size` at `scale`, filled with `background`."""
    inner = max(1, round(size * scale))
    resized = img.resize((inner, inner), Image.LANCZOS)
    canvas = Image.new("RGB", (size, size), background)
    offset = (size - inner) // 2
    canvas.paste(resized, (offset, offset))
    return canvas


def circular(img: Image.Image) -> Image.Image:
    """Mask a square RGB image to a circle, keeping antialiased edges."""
    mask = Image.new("L", img.size, 0)
    draw = ImageDraw.Draw(mask)
    draw.ellipse((0, 0, img.size[0] - 1, img.size[1] - 1), fill=255)
    out = img.convert("RGBA")
    out.putalpha(mask)
    return out


def background_xml(colour: tuple[int, int, int]) -> str:
    hex_colour = "#{:02X}{:02X}{:02X}".format(*colour)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Adaptive-icon background: solid tone sampled from the emblem artwork.\n"
        "     Generated by tools/make_icons.py - edit the artwork, not this file. -->\n"
        '<shape xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:shape="rectangle">\n'
        f'    <solid android:color="{hex_colour}" />\n'
        "</shape>\n"
    )


def main() -> int:
    if not SOURCE.exists():
        raise SystemExit(f"missing artwork: {SOURCE}")
    source = Image.open(SOURCE).convert("RGBA")
    if source.width != source.height:
        side = min(source.size)
        left = (source.width - side) // 2
        top = (source.height - side) // 2
        source = source.crop((left, top, left + side, top + side))

    background = edge_colour(source)
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()[:16]
    print(f"[icons] source {SOURCE.relative_to(ROOT)} {source.width}x{source.height} sha256:{digest}")
    print(f"[icons] background #{background[0]:02X}{background[1]:02X}{background[2]:02X}")

    for density, size in DENSITIES.items():
        folder = RES / f"mipmap-{density}"
        folder.mkdir(parents=True, exist_ok=True)
        square = on_canvas(source, size, 1.0, background)
        square.save(folder / "ic_launcher.png", optimize=True)
        circular(on_canvas(source, size, ROUND_SCALE, background)).save(
            folder / "ic_launcher_round.png", optimize=True
        )
        print(f"[icons] mipmap-{density}/ic_launcher.png {size}x{size}")

    # Adaptive foreground: transparent canvas, artwork inside the safe zone.
    art = RES / "drawable-nodpi"
    art.mkdir(parents=True, exist_ok=True)
    inner = max(1, round(ADAPTIVE_SIZE * FOREGROUND_SCALE))
    layer = Image.new("RGBA", (ADAPTIVE_SIZE, ADAPTIVE_SIZE), (0, 0, 0, 0))
    scaled = source.resize((inner, inner), Image.LANCZOS)
    offset = (ADAPTIVE_SIZE - inner) // 2
    layer.paste(scaled, (offset, offset))
    layer.save(art / "ic_launcher_art.png", optimize=True)
    print(f"[icons] drawable-nodpi/ic_launcher_art.png {ADAPTIVE_SIZE}x{ADAPTIVE_SIZE}")

    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "drawable" / "ic_launcher_background.xml").write_text(background_xml(background), encoding="utf-8")
    print("[icons] drawable/ic_launcher_background.xml")

    # In-app brand mark used by the web UI header (same artwork, no mask).
    web_img = ROOT / "app" / "assets" / "www" / "img"
    web_img.mkdir(parents=True, exist_ok=True)
    source.resize((WEB_SIZE, WEB_SIZE), Image.LANCZOS).save(web_img / "emblem.png", optimize=True)
    print(f"[icons] assets/www/img/emblem.png {WEB_SIZE}x{WEB_SIZE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
